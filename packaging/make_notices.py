#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.txt: the licence of every crate compiled into
bahth.exe for the three Windows targets (normal dependencies only; build and
dev dependencies are not shipped), with the licence files each crate ships.

    python3 packaging/make_notices.py           # rewrite the file
    python3 packaging/make_notices.py --check   # fail if it is out of date

The MSIX packages carry it (packaging/msix/make_layout.py) and About links
to it. Rerun after any Cargo.lock change; store.yml checks it.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD-PARTY-NOTICES.txt")
TARGETS = ["x86_64-pc-windows-msvc", "i686-pc-windows-msvc", "aarch64-pc-windows-msvc"]
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice|copyright|unlicense)([-_.].*)?$", re.I)


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def shipped(meta):
    """Package ids reachable from the root through normal dependencies."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, todo = set(), [root]
    while todo:
        cur = todo.pop()
        for dep in nodes[cur]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    return seen


def license_texts(pkg):
    folder = os.path.dirname(pkg["manifest_path"])
    texts = []
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if LICENSE_FILE.match(name) and os.path.isfile(path):
            with open(path, encoding="utf-8", errors="replace") as f:
                texts.append((name, f.read().strip().replace("\r\n", "\n")))
    if pkg.get("license_file"):
        path = os.path.join(folder, pkg["license_file"])
        if os.path.isfile(path) and not any(n == os.path.basename(path) for n, _ in texts):
            with open(path, encoding="utf-8", errors="replace") as f:
                texts.append((os.path.basename(path), f.read().strip().replace("\r\n", "\n")))
    return texts


def render():
    packages = {}
    for target in TARGETS:
        meta = metadata(target)
        by_id = {p["id"]: p for p in meta["packages"]}
        for pid in shipped(meta):
            p = by_id[pid]
            packages[(p["name"], p["version"])] = p
    lines = [
        "InstaFind (bahth.exe) — third-party notices",
        "",
        "InstaFind is MIT licensed (LICENSE). It includes the following open-source",
        "crates, under the licences below. Generated by packaging/make_notices.py",
        "from Cargo.lock; do not edit by hand.",
        "",
        f"{len(packages)} crates:",
        "",
    ]
    for (name, version), p in sorted(packages.items()):
        lines.append(f"  {name} {version} — {p.get('license') or 'see licence file'}")
    # Each distinct licence text once (most crates share the Apache and MIT
    # texts word for word), referred to by number from each crate.
    texts, numbers = [], {}
    for (name, version), p in sorted(packages.items()):
        lines += ["", "=" * 78, f"{name} {version}", f"Licence: {p.get('license') or 'see below'}"]
        if p.get("repository"):
            lines.append(f"Source: {p['repository']}")
        files = license_texts(p)
        if not files:
            lines.append("(The crate ships no licence file; the licence named above applies.)")
        for fname, text in files:
            key = re.sub(r"\s+", " ", text)
            if key not in numbers:
                texts.append(text)
                numbers[key] = len(texts)
            lines.append(f"{fname}: text [{numbers[key]}] below")
    for i, text in enumerate(texts, 1):
        lines += ["", "#" * 78, f"[{i}]", "", text]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if THIRD-PARTY-NOTICES.txt is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        try:
            with open(OUT, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            sys.exit("THIRD-PARTY-NOTICES.txt is out of date: run python3 packaging/make_notices.py")
        print("THIRD-PARTY-NOTICES.txt is current")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
